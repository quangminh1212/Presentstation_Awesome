#!/usr/bin/env python3
# Copy the already-fetched raw README of every repo listed in each category
# README.md into that category folder, named github.com.owner.repo.md.
# If a repo has no upstream README, write a placeholder README instead
# (link + stars + description parsed from the category index).
# Source of truth = the curated category README.md files (the split index).
# READMEs were previously fetched into readmes/<cat>/owner__repo.md.
import os, re, shutil

ROOT = r"C:\Dev\PresentstationTool"
READMES = os.path.join(ROOT, "readmes")
CATS = ["featured", "ai-generators", "mcp-servers", "agent-skills",
        "html-slide-frameworks", "markdown-slides", "pptx-ooxml",
        "themes-templates", "knowledge-bases"]

# lookup: (owner.lower(), repo.lower()) -> fetched file path
lookup = {}
for dirpath, _, filenames in os.walk(READMES):
    for fn in filenames:
        if fn.endswith(".md"):
            base = fn[:-3]
            if "__" in base:
                owner, repo = base.split("__", 1)
                lookup.setdefault((owner.lower(), repo.lower()),
                                  os.path.join(dirpath, fn))

# match the index bullet: - [name](url) — ★ stars — description
line_re = re.compile(
    r'^- \[[^\]]+\]\((https?://github\.com/([^/)\s]+)/([^/)\s]+))'
    r'(?:\s*[—-]\s*★\s*([\d,]+))?(?:\s*[—-]\s*(.*))?')
url_re = re.compile(r'\(https?://github\.com/([^/)\s]+)/([^/)\s]+)\)')

report = []
for cat in CATS:
    src = os.path.join(ROOT, cat, "README.md")
    if not os.path.exists(src):
        continue
    with open(src, encoding="utf-8") as f:
        lines = f.readlines()
    copied = placeholder = no_readme = missing = total = 0
    seen = set()
    for line in lines:
        m = line_re.search(line)
        if not m:
            # fallback plain url match (some lines differ)
            u = url_re.search(line)
            if not u:
                continue
            url, owner, repo = "", u.group(1), u.group(2)
            stars = desc = None
        else:
            url, owner, repo, stars, desc = m.groups()
        key = (owner.lower(), repo.lower())
        if key in seen:
            continue
        seen.add(key)
        total += 1
        outname = f"github.com.{owner}.{repo}.md"
        outpath = os.path.join(ROOT, cat, outname)
        if os.path.exists(outpath):
            # already handled in a previous run
            if os.path.getsize(outpath) == 0:
                placeholder += 1
            else:
                copied += 1
            continue
        fpath = lookup.get(key)
        if fpath and os.path.getsize(fpath) > 0:
            shutil.copy2(fpath, outpath)
            copied += 1
        else:
            # no upstream README -> write a placeholder
            body = (
                f"# {owner}/{repo}\n\n"
                f"**Repository:** https://github.com/{owner}/{repo}\n"
            )
            if stars:
                body += f"**Stars:** {stars}\n"
            if desc:
                desc = desc.strip()
                if desc:
                    body += f"**Description:** {desc}\n"
            body += (
                "\n*No README file is available for this repository on "
                "GitHub; this placeholder was generated by the curator.*\n"
            )
            with open(outpath, "w", encoding="utf-8") as wf:
                wf.write(body)
            if fpath:
                no_readme += 1
            else:
                missing += 1
            placeholder += 1
    report.append((cat, total, copied, placeholder, no_readme, missing))

with open(os.path.join(ROOT, "research", "copy_readmes_report.txt"),
          "w", encoding="utf-8") as rf:
    for cat, total, copied, placeholder, no_readme, missing in report:
        row = (f"{cat}: listed={total} copied={copied} "
               f"placeholder={placeholder} (no_readme={no_readme} "
               f"missing={missing})")
        print(row)
        rf.write(row + "\n")
